import { expect, test } from '@playwright/test'

test('epico stellari : taux du paquet sélectionné, achat à 700 et ouverture', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  const showRates = async (epico: boolean) => {
    await page.getByRole('button', { name: 'taux de drop', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Taux de drop', exact: true })
    const rarity = dialog.locator('section').filter({ has: page.getByRole('heading', { name: 'Rareté', exact: true }) })
    await expect(rarity.locator('dd')).toHaveText(epico ? ['0 %', '0 %', '0 %', '91 %', '9 %'] : ['57 %', '24 %', '12 %', '5 %', '2 %'])
    await expect(dialog.locator('section').filter({ has: page.getByRole('heading', { name: 'Finition', exact: true }) }).locator('dd')).toHaveText(['81 %', '15 %', '4 %'])
    await expect(dialog.locator('section').filter({ has: page.getByRole('heading', { name: 'Illustration', exact: true }) }).locator('dd')).toHaveText(['92 %', '8 %'])
    await expect(dialog.getByRole('heading')).toHaveText(['Taux de drop', 'Rareté', 'Finition', 'Illustration'])
    await dialog.getByRole('button', { name: 'Fermer', exact: true }).click()
  }
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Ouvrir le booster epico stellari', exact: true })).toHaveCount(0)
  await showRates(false)
  await page.getByRole('link', { name: 'Boutique', exact: true }).click()
  await showRates(false)
  await page.locator('.booster-carousel-track').press('End')
  const buy = page.getByRole('button', { name: 'Acheter epico stellari pour 700 fragments', exact: true })
  await expect(buy).toBeDisabled()
  await showRates(true)
  await page.locator('.booster-carousel-track').press('Home')
  await showRates(false)
  await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    await db.player.update('local', { fragments: 700 })
  })
  await page.locator('.booster-carousel-track').press('End')
  await expect(buy).toBeEnabled()
  await page.screenshot({ path: `artifacts/epico-stellari-shop-${test.info().project.name}.png`, fullPage: true })
  await buy.click()
  await expect(page.getByRole('button', { name: 'epico stellari ajouté', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Vos boosters', exact: true }).click()
  await page.getByRole('button', { name: 'Booster suivant', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ouvrir le booster Anima Isekai', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Booster suivant', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ouvrir le booster epico stellari', exact: true })).toBeEnabled()
  await showRates(true)
  await page.locator('.booster-carousel-track').press('Home')
  await showRates(false)
  await page.locator('.booster-carousel-track').press('End')
  await page.getByRole('button', { name: 'Ouvrir le booster epico stellari', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Révéler la première carte', exact: true })).toBeVisible()
  const state = await page.evaluate(async () => {
    const dbPath = '/src/storage/database.ts', cardPath = '/src/data/cards.ts'
    const { db } = await import(dbPath), { cardById } = await import(cardPath)
    const [opening] = await db.openings.toArray()
    return { player: await db.player.get('local'), stock: await db.boosterStock.get('epico-stellari'), payment: opening.payment, rarities: opening.results.map((card: { cardId: string }) => cardById.get(card.cardId).rarity) }
  })
  expect(state.player).toMatchObject({ fragments: 0, freePackStock: 5 })
  expect(state.stock.quantity).toBe(0)
  expect(state.payment).toBe('shop')
  expect(state.rarities).toHaveLength(5)
  expect(state.rarities.every((rarity: string) => ['epic', 'legendary'].includes(rarity))).toBe(true)
})
