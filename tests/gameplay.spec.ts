test('échanges : contacts, transfert signé et antirejeu avec le parcours actuel', async ({ page, browser, baseURL }) => {
  test.setTimeout(90_000) // Two isolated players, cryptography and repeated full-page navigations on WebKit.
  const secondContext = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 } })
  const second = await secondContext.newPage()
  try {
    // Clipboard permissions are browser-specific; exercise the same UI with an isolated clipboard.
    for (const tab of [page, second]) await tab.addInitScript(() => {
      let clipboard = ''
      Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (text: string) => { clipboard = text }, readText: async () => clipboard }, configurable: true })
    })
    const contactCodes: string[] = []
    for (const tab of [page, second]) {
      await tab.goto('/echanges')
      await tab.bringToFront()
      await tab.getByRole('button', { name: 'Ajouter un ami', exact: true }).first().click()
      await tab.getByRole('button', { name: 'Copier mon code ami', exact: true }).click()
      await expect(tab.getByRole('button', { name: 'Code copié !', exact: true })).toBeVisible()
      contactCodes.push(await tab.evaluate(() => navigator.clipboard.readText()))
      await tab.getByRole('button', { name: 'Fermer', exact: true }).click()
    }
    for (const [tab, code, name] of [[page, contactCodes[1], 'B'], [second, contactCodes[0], 'A']] as const) {
      await tab.bringToFront()
      await tab.getByRole('button', { name: 'Ajouter un ami', exact: true }).first().click()
      await tab.getByRole('textbox', { name: 'Nom de l’ami', exact: true }).fill(name)
      await tab.evaluate(value => navigator.clipboard.writeText(value), code)
      await tab.getByRole('button', { name: 'Coller son code ami', exact: true }).click()
      await expect(tab.getByRole('button', { name: 'Code ami collé !', exact: true })).toBeVisible()
      await tab.getByRole('dialog').getByRole('button', { name: 'Ajouter', exact: true }).click()
      await expect(tab.locator('.friend-row')).toHaveCount(1)
    }
    await page.bringToFront()
    await page.goto('/')
    await page.getByRole('button', { name: 'Ouvrir le booster Memory Frame', exact: true }).click()
    await page.getByRole('button', { name: 'Révéler la première carte', exact: true }).click()
    for (let i = 1; i < 5; i++) await page.locator('.opening-card-area .card').click()
    await page.locator('.opening-card-area .card').click()
    await expect(page.locator('.recap-grid .card')).toHaveCount(5)
    await expect(page.locator('.recap-caption').first()).toHaveCSS('visibility', 'hidden')
    expect((await page.locator('.recap-caption').first().boundingBox())!.height).toBeGreaterThan(0)
    await page.goto('/collection')
    await page.locator('.collection-grid .card').first().click()
    await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
    await page.getByRole('button', { name: 'Envoyer à B', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Code de transfert copié !', exact: true })).toBeVisible()
    const transfer = await page.evaluate(() => navigator.clipboard.readText())
    expect(transfer).toMatch(/^TR2\./)
    await second.bringToFront()
    await second.getByRole('tab', { name: 'Recevoir', exact: true }).click()
    await second.evaluate(value => navigator.clipboard.writeText(value), transfer)
    await second.getByRole('button', { name: 'Coller le code', exact: true }).click()
    await expect(second.getByRole('status')).toContainText('Code de transfert prêt')
    await second.getByRole('button', { name: 'Recevoir', exact: true }).click()
    const received = second.getByRole('dialog', { name: 'Carte reçue', exact: true })
    await expect(received.getByRole('status')).toHaveText('Vous avez reçu une carte')
    await expect(received.locator('.card')).toHaveCount(1)
    const messageBox = await received.getByRole('status').boundingBox()
    expect(messageBox!.y + messageBox!.height).toBeLessThan(844)
    await expect(received.getByRole('button', { name: /Envoyer|Recycler/ })).toHaveCount(0)
    await second.screenshot({ path: 'artifacts/carte-recue-mobile.png', fullPage: true })
    await received.getByRole('button', { name: 'Fermer', exact: true }).click()
    await expect(second.getByRole('button', { name: 'Recevoir', exact: true })).toBeDisabled()
    await second.goto('/collection')
    await expect(second.locator('.title-with-count > span')).toHaveText('1')
    await page.goto('/collection')
    await expect(page.locator('.title-with-count > span')).toHaveText('4')
    await second.bringToFront()
    await second.goto('/echanges')
    await second.getByRole('tab', { name: 'Recevoir', exact: true }).click()
    await second.evaluate(value => navigator.clipboard.writeText(value), transfer)
    await second.getByRole('button', { name: 'Coller le code', exact: true }).click()
    await second.getByRole('button', { name: 'Recevoir', exact: true }).click()
    await expect(second.getByRole('alert')).toHaveText('Ce code a déjà été utilisé.')
    await page.goto('/echanges?onglet=envois')
    await expect(page.locator('.transfer-row')).toHaveCount(1)
    await page.getByRole('button', { name: 'Copier', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Code copié !', exact: true })).toBeVisible()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(transfer)
  } finally { await secondContext.close() }
})
