test('au clavier et en reduced-motion, carte et filtres restent accessibles', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Ouvrir le booster Phantom Blood', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Révéler la première carte', exact: true }).press('Enter')
  for (let i = 1; i < 5; i++) await page.locator('.opening-card-area .card').press('Enter')
  await page.locator('.opening-card-area .card').press('Enter')
  await page.goto('/collection')
  await page.locator('.collection-grid .card').first().press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Rareté', exact: true }).press('ArrowDown')
  await expect(page.getByRole('menu', { name: 'Rareté' })).toBeVisible()
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter')
  await expect(page.getByRole('menuitemcheckbox', { name: 'Peu commune', exact: true })).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: /^Rareté/ })).toBeFocused()
})
test('échanges : contacts dans des dialogues, transfert et antirejeu', async ({ page, browser, baseURL }) => {
  const secondContext = await browser.newContext({ baseURL })
  const second = await secondContext.newPage()
  try {
    await page.goto('/'); await openPack(page)
    await page.goto('/echanges'); await second.goto('/echanges')
    const codes: string[] = []
    for (const tab of [page, second]) {
      await tab.getByRole('button', { name: 'Mon contact', exact: true }).click()
      codes.push(await tab.getByRole('textbox', { name: 'Mon code de contact', exact: true }).inputValue())
      await tab.getByRole('button', { name: 'Fermer', exact: true }).click()
    }
    for (const [tab, code, name] of [[page, codes[1], 'B'], [second, codes[0], 'A']] as const) {
      await tab.getByRole('button', { name: 'Ajouter un ami', exact: true }).click()
      await tab.getByRole('textbox', { name: 'Nom', exact: true }).fill(name)
      await tab.getByRole('textbox', { name: 'Code de contact', exact: true }).fill(code)
      await tab.getByRole('dialog').getByRole('button', { name: 'Ajouter', exact: true }).click()
      await expect(tab.locator('.friend-row')).toHaveCount(1)
    }
    await page.goto('/collection'); await page.locator('.collection-grid .card').first().click()
    await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
    await page.getByRole('button', { name: 'Destinataire', exact: true }).click()
    await page.getByRole('menuitemradio', { name: 'B', exact: true }).click()
    await page.getByRole('button', { name: 'Créer le transfert', exact: true }).click()
    const transfer = await page.getByRole('textbox', { name: 'Code de transfert généré' }).inputValue()
    await second.getByRole('tab', { name: 'Recevoir', exact: true }).click()
    await second.getByRole('textbox', { name: 'Code de transfert', exact: true }).fill(transfer)
    await second.getByRole('button', { name: 'Recevoir', exact: true }).click()
    await expect(second.getByRole('status')).toContainText('rejoint votre collection')
    await second.getByRole('textbox', { name: 'Code de transfert', exact: true }).fill(transfer)
    await second.getByRole('button', { name: 'Recevoir', exact: true }).click()
    await expect(second.getByRole('alert')).toHaveText('Ce code a déjà été utilisé.')
    await page.goto('/echanges'); await page.getByRole('tab', { name: 'Envois 1', exact: true }).click()
    await page.getByText('Afficher le code', { exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Code de transfert sauvegardé' })).toHaveValue(transfer)
  } finally { await secondContext.close() }
})
