test('mouvement : aucun débit avant alignement, puis achat de la carte affichée', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/boutique')
  const selection = page.locator('.weekly-selection'), buy = selection.locator('.shop-buy'), track = selection.locator('.booster-carousel-track')
  await expect(buy).toBeVisible()
  await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path), cardsPath = '/src/data/cards.ts', { cards } = await import(cardsPath)
    const shop = await db.weeklyShop.get('current')
    shop.offers = cards.slice(0, 3).map((card: { id: string }, i: number) => ({ id: String(i), cardId: card.id, finish: 'normal', artVariant: 'standard', price: (i + 1) * 100, sold: false }))
    await db.player.update('local', { fragments: 1000 }); await db.weeklyShop.put(shop)
  })
  await expect(selection.locator('.booster-carousel-dots > span')).toHaveCount(4)
  await selection.evaluate(el => { el.querySelector<HTMLButtonElement>('.carousel-next')!.click(); el.querySelector<HTMLButtonElement>('.shop-buy')!.click() })
  await expect(buy).toBeDisabled()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(buy).toHaveText('Acheter 100')
  await expect(buy).toBeEnabled()
  const balance = await page.evaluate(async () => { const path = '/src/storage/database.ts', { db } = await import(path); return (await db.player.get('local')).fragments })
  expect(balance).toBe(1000)
  await selection.getByRole('button', { name: 'Offre suivante', exact: true }).click()
  await expect(buy).toHaveText('Acheter 200')
  await expect(buy).toBeEnabled()
  await buy.click()
  await expect(buy).toHaveText('Ajouté')
  await expect(buy).toHaveText('Épuisée 200')
  await expect(selection.locator('.booster-carousel-slide[aria-hidden="false"] .showcase-card')).toHaveClass(/is-sold/)
  await track.press('End')
  await expect(buy).toHaveText('Acheter 300')
  await expect(buy).toBeEnabled()
  const purchased = await page.evaluate(async () => { const path = '/src/storage/database.ts', { db } = await import(path); return { fragments: (await db.player.get('local')).fragments, cards: await db.drops.toArray(), offer: (await db.weeklyShop.get('current')).offers[1] } })
  expect(purchased.fragments).toBe(800); expect(purchased.cards).toHaveLength(1)
  expect(purchased.cards[0].cardId).toBe(purchased.offer.cardId)
})

