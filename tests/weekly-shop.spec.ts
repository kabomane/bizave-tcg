test('minuit renouvelle le quotidien sans perdre les cartes ni modifier la semaine', async ({ page }) => {
  await page.locator('#daily .card-zone .shop-buy').click()
  await page.getByRole('button', { name: 'Acheter le lot', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Lot acheté', exact: true })).toBeDisabled()
  const before = await page.evaluate(async () => { const path = '/src/storage/database.ts', { db } = await import(path); return { daily: await db.dailyShop.get('current'), weekly: await db.weeklyShop.get('current') } })
  await page.clock.setFixedTime(new Date(before.daily.renewAt))
  await expect.poll(() => page.evaluate(async () => { const path = '/src/storage/database.ts', { db } = await import(path); return (await db.dailyShop.get('current')).dayStart })).toBe(before.daily.renewAt)
  await expect(page.getByRole('button', { name: 'Acheter le lot', exact: true })).toBeEnabled()
  const after = await page.evaluate(async () => { const path = '/src/storage/database.ts', { db } = await import(path); return { daily: await db.dailyShop.get('current'), weekly: await db.weeklyShop.get('current'), drops: await db.drops.count(), rows: await db.dailyShop.count() } })
  expect(after.daily.dayStart).toBe(before.daily.renewAt)
  expect(after.daily.bundle.owned).toBe(0); expect(after.weekly).toEqual(before.weekly)
  expect(after.drops).toBe(1); expect(after.rows).toBe(1)
  await page.evaluate(async () => { const path = '/src/storage/database.ts', { db } = await import(path); await db.dailyShop.update('current', { cards: [] }) })
  await expect(page.locator('#daily .card-zone')).toHaveCount(0)
  await expect(page.locator('.daily-grid')).toHaveClass(/has-no-cards/)
})

test('taux globaux consultables pour chaque édition et les deux vitrines', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Taux de drop', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Taux de drop', exact: true })
  for (const [title, expected] of [['Cartes du jour', ['57 %', '24 %', '12 %', '5 %', '2 %']], ['Vitrine de la semaine', ['30 %', '25 %', '20 %', '13 %', '12 %']], ['legenda completa', ['0 %', '0 %', '0 %', '0 %', '100 %']]] as const) {
    await dialog.getByRole('button', { name: title, exact: true }).click()
    await expect(dialog.locator('.booster-carousel-slide[aria-hidden="false"] dd')).toHaveText([...expected])
  }
  const current = dialog.locator('.booster-carousel-slide[aria-hidden="false"]')
  await dialog.getByRole('button', { name: 'Catégorie suivante', exact: true }).click()
  await expect(current.locator('h2')).toHaveText('Finition')
  await expect(current.locator('dd')).toHaveText(['81 %', '15 %', '4 %'])
  await dialog.locator('.booster-carousel-track').press('End')
  await expect(current.locator('h2')).toHaveText('Illustration')
  await expect(current.locator('dd')).toHaveText(['92 %', '8 %'])
  const bounds = await dialog.boundingBox()
  expect(bounds!.width).toBe(390)
  expect(bounds!.height).toBe(844)
  await dialog.locator('.booster-carousel-track').press('Home')
  for (const [width, height] of [[320, 568], [390, 844], [844, 390], [1440, 900]]) {
    await page.setViewportSize({ width, height })
    expect(await dialog.evaluate(el => el.scrollHeight <= el.clientHeight && el.scrollWidth <= el.clientWidth)).toBe(true)
    const lastRate = await current.locator('dd').last().boundingBox()
    expect(lastRate!.y + lastRate!.height).toBeLessThanOrEqual(height)
  }
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Taux de drop', exact: true })).toBeFocused()
})

