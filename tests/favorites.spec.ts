import { expect, test } from '@playwright/test'

test('favoris : variantes, filtre, piles et suppression de la dernière copie', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/collection')
  await expect(page.getByRole('heading', { name: 'Collection', exact: true })).toBeVisible()
  await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    await db.drops.bulkAdd([
      { cardId: 't-classique', finish: 'normal', artVariant: 'standard' },
      { cardId: 't-classique', finish: 'normal', artVariant: 'standard' },
      { cardId: 't-classique', finish: 'glossy', artVariant: 'fullArt' },
      { cardId: 'op-thomas', finish: 'normal', artVariant: 'standard' },
    ].map((card, index) => ({ ...card, dropId: crypto.randomUUID(), status: 'owned', acquiredAt: 1 + index, updatedAt: 1 + index })))
  })
  const grid = page.locator('.collection-grid').first(), star = page.getByRole('button', { name: 'Afficher uniquement les favoris', exact: true })
  await expect(grid.locator('.card')).toHaveCount(3)
  await grid.locator('.card[data-art="fullArt"]').click()
  await page.getByRole('button', { name: 'Ajouter aux favoris', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Retirer des favoris', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const starIcon = await page.locator('.favorite-toggle svg').boundingBox(), closeIcon = await page.getByRole('dialog').getByRole('button', { name: 'Fermer', exact: true }).locator('svg').boundingBox()
  expect(starIcon!.width).toBe(18); expect(closeIcon!.width).toBe(starIcon!.width)
  expect(closeIcon!.height).toBe(starIcon!.height)
  await page.screenshot({ path: `artifacts/favori-detail-${test.info().project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Fermer', exact: true }).click()
  await star.click()
  await expect(grid.locator('.card')).toHaveCount(1)
  await expect(grid.locator('.card')).toHaveAttribute('data-art', 'fullArt')
  await page.getByRole('searchbox').fill('Roronoa')
  await expect(grid.locator('.card')).toHaveCount(0)
  await page.getByRole('searchbox').fill('')
  await expect(grid.locator('.card')).toHaveCount(1)
  await page.reload()
  await expect(grid.locator('.card')).toHaveCount(3)
  await page.getByRole('button', { name: 'Affichage', exact: true }).click()
  await page.getByRole('button', { name: 'Par carte', exact: true }).click()
  await page.getByRole('button', { name: 'Fermer', exact: true }).click()
  await page.getByRole('searchbox').fill('Thomas classique')
  await expect(page.locator('.collection-pile')).toHaveCount(1)
  await page.locator('.collection-pile .card').click()
  await expect(page.locator('.stack-grid .card')).toHaveCount(2)
  await page.locator('.stack-grid .card[data-art="fullArt"]').click()
  await expect(page.getByRole('button', { name: 'Retirer des favoris', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Retour à la pile', exact: true }).click()
  await page.getByRole('button', { name: 'Fermer', exact: true }).click()
  await star.click()
  await expect(grid.locator('.card')).toHaveCount(1)
  await grid.locator('.card').click()
  await page.getByRole('button', { name: /^Recycler ·/ }).click()
  await page.getByRole('button', { name: 'Recycler', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Aucune carte', exact: true })).toBeVisible()
  expect(await page.evaluate(async () => { const path = '/src/storage/database.ts', { db } = await import(path); return db.favorites.count() })).toBe(0)
  await star.click()
  await expect(grid.locator('.card')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
