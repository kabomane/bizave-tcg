import { expect, test } from '@playwright/test'

test('nouveau joueur, contrôle au rechargement, continuer et bouton de test', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/collection')
  await expect(page.getByRole('heading', { name: 'Collection', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('updated'))).toBe('1')
  await page.evaluate(() => localStorage.setItem('updated', '0'))
  await page.getByRole('link', { name: 'Atelier', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Atelier', exact: true })).toBeVisible()
  await page.reload()
  await expect(page).toHaveURL(/\/mise-a-jour$/)
  await expect(page.getByRole('heading', { name: 'Bizave TCG a été mis à jour', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('updated'))).toBe('0')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Continuer', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/mise-a-jour-${test.info().project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Continuer', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('button', { name: 'Ouvrir le booster Memory Frame', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('updated'))).toBe('1')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Ouvrir le booster Memory Frame', exact: true })).toBeVisible()
  await page.goto('/parametres')
  await page.getByRole('switch', { name: 'Page de mise à jour', exact: true }).check()
  await expect(page.getByRole('switch', { name: 'Page de mise à jour', exact: true })).toBeChecked()
  expect(await page.evaluate(() => localStorage.getItem('updated'))).toBe('0')
  await page.reload()
  await expect(page).toHaveURL(/\/mise-a-jour$/)
})

test('ancien joueur sans marqueur, prochaine version et retour à une version inférieure', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Ouvrir le booster Memory Frame', exact: true })).toBeVisible()
  await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    await db.player.update('local', { fragments: 321 })
    localStorage.removeItem('updated')
  })
  await page.reload()
  await expect(page).toHaveURL(/\/mise-a-jour$/)
  await page.getByRole('button', { name: 'Continuer', exact: true }).click()
  await expect(page.getByLabel('321 fragments', { exact: true })).toBeVisible()
  await page.route('**/src/data/update.ts*', async route => {
    const response = await route.fetch()
    await route.fulfill({ response, body: (await response.text()).replace('UPDATE_VERSION = 1', 'UPDATE_VERSION = 2') })
  })
  await page.reload()
  await expect(page).toHaveURL(/\/mise-a-jour$/)
  await page.getByRole('button', { name: 'Continuer', exact: true }).click()
  await expect(page.getByLabel('321 fragments', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('updated'))).toBe('2')
  await page.unroute('**/src/data/update.ts*')
  await page.reload()
  await expect(page.getByLabel('321 fragments', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Bizave TCG a été mis à jour', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('updated'))).toBe('2')
})
