import { expect, test } from '@playwright/test'

test('atelier : les favoris sont exclus des deux modes et protégés du recyclage en lot', async ({ page }) => {
  await page.goto('/atelier')
  await expect(page.getByRole('heading', { name: 'Atelier', exact: true })).toBeVisible()
  await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    const favorite = { cardId: 't-classique', finish: 'normal', artVariant: 'standard' }
    await db.drops.bulkAdd([favorite, favorite, { ...favorite, cardId: 'op-thomas' }, { ...favorite, cardId: 'op-thomas' }].map((card, i) => ({ ...card, dropId: crypto.randomUUID(), status: 'owned', acquiredAt: i, updatedAt: i })))
    await db.favorites.put({ ...favorite, key: 't-classique::normal::standard' })
  })
  await expect(page.locator('.duplicate-row')).toHaveCount(1)
  await expect(page.locator('.duplicate-row strong')).toHaveText('Roronoa Thomas')
  await expect(page.locator('.title-with-count > span')).toHaveText('1')
  await page.getByRole('button', { name: 'Vos doublons', exact: true }).click()
  await expect(page.locator('.title-with-count > span')).toHaveText('2')
  await page.getByLabel('Tout sélectionner', { exact: true }).check()
  await page.getByRole('button', { name: /^Recycler/ }).click()
  await expect(page.getByRole('dialog')).toContainText('2 cartes → 2 fragments')
  await page.getByRole('dialog').getByRole('button', { name: 'Recycler', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Aucune carte à recycler.', exact: true })).toBeVisible()
  const state = await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    return { owned: await db.drops.where('status').equals('owned').count(), favorites: await db.favorites.count() }
  })
  expect(state).toEqual({ owned: 2, favorites: 1 })
})

test('atelier : filtres combinés, sélection visible et mode dernières copies', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/atelier')
  await expect(page.getByRole('heading', { name: 'Atelier', exact: true })).toBeVisible()
  await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    const rows = [
      ['t-classique', 'normal', 'standard'], ['t-classique', 'normal', 'standard'],
      ['t-classique', 'normal', 'fullArt'], ['t-classique', 'glossy', 'standard'],
      ['op-thomas', 'normal', 'standard'], ['op-thomas', 'normal', 'standard'], ['jojo-thomas', 'normal', 'standard'],
    ].map(([cardId, finish, artVariant], index) => ({ dropId: crypto.randomUUID(), cardId, finish, artVariant, status: 'owned', acquiredAt: index, updatedAt: index }))
    await db.drops.bulkAdd(rows)
    await db.drops.add({ ...rows[0], dropId: crypto.randomUUID(), status: 'outgoing' })
  })
  const mode = page.getByRole('button', { name: /^(Vos doublons|Toutes vos cartes)$/ })
  await expect(mode).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.duplicate-row')).toHaveCount(2)
  const filter = async (menu: string, option: string) => {
    await page.getByRole('button', { name: new RegExp('^' + menu) }).click()
    await page.getByRole('menuitemcheckbox', { name: option, exact: true }).click()
    await page.keyboard.press('Escape')
  }
  await filter('Boosters', 'Anima Isekai')
  await filter('Rareté', 'Commune')
  await filter('Finitions', 'Mate')
  await filter('Finitions', 'Classique')
  await expect(page.locator('.duplicate-row')).toHaveCount(1)
  await expect(page.locator('.duplicate-row strong')).toHaveText('Roronoa Thomas')
  await page.getByLabel('Tout sélectionner', { exact: true }).check()
  await expect(page.locator('.recycle-summary')).toContainText('1 sélectionné')
  await filter('Finitions', 'Full Art')
  await expect(page.locator('.recycle-summary')).toContainText('0 sélectionné')
  await filter('Finitions', 'Full Art')
  await mode.click()
  await expect(page.locator('.duplicate-row')).toContainText('2 cartes')
  await page.getByLabel('Tout sélectionner', { exact: true }).check()
  await page.getByRole('button', { name: /^Recycler/ }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('2 cartes → 2 fragments')
  await expect(dialog).toContainText('dernière copie de 1 variante')
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  await expect(page.locator('.recycle-summary')).toContainText('2 sélectionnés')
  await mode.click()
  await expect(page.locator('.recycle-summary')).toContainText('0 sélectionné')
  await mode.click()
  await page.getByLabel('Tout sélectionner', { exact: true }).check()
  await page.getByRole('button', { name: /^Recycler/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Recycler', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Aucune carte ne correspond.', exact: true })).toBeVisible()
  await page.reload()
  await expect(mode).toHaveAttribute('aria-pressed', 'false')
  await mode.click()
  await expect(page.locator('.title-with-count > span')).toHaveText('5')
  await page.getByLabel('Tout sélectionner', { exact: true }).check()
  await page.getByRole('button', { name: /^Recycler/ }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('5 cartes → 17 fragments')
  await expect(dialog).toContainText('dernière copie de 4 variantes')
  await page.screenshot({ path: 'artifacts/atelier-confirmation-mobile.png', fullPage: true })
  await dialog.getByRole('button', { name: 'Recycler', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Votre collection est vide.', exact: true })).toBeVisible()
  const state = await page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    return { owned: await db.drops.where('status').equals('owned').count(), outgoing: await db.drops.where('status').equals('outgoing').count(), player: await db.player.get('local'), records: await db.recycling.count() }
  })
  expect(state.owned).toBe(0)
  expect(state.outgoing).toBe(1)
  expect(state.player.fragments).toBe(19)
  expect(state.records).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
