import { expect, test } from '@playwright/test'

for (const width of [390, 1280]) test(`pile conservée au retour et détruite à la fermeture (${width}px)`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 })
  await page.goto('/collection')
  await expect(page.getByRole('heading', { name: 'Collection', exact: true })).toBeVisible()
  await page.evaluate(async () => {
    const databasePath = '/src/storage/database.ts', settingsPath = '/src/settings/useSettings.ts'
    const { db } = await import(databasePath), { updateSettings } = await import(settingsPath)
    updateSettings({ collectionDisplay: { sort: 'obtained', direction: 'desc', groupBy: 'card', duplicates: 'show' } })
    await db.drops.bulkAdd(Array.from({ length: 22 }, (_, i) => ({ cardId: i < 20 ? 't-classique' : 'm-classique', finish: 'normal', artVariant: 'standard', dropId: crypto.randomUUID(), status: 'owned', acquiredAt: i + 1, updatedAt: i + 1 })))
  })
  await page.reload()
  await expect(page.locator('.collection-pile')).toHaveCount(2)
  const grid = page.locator('.collection-grid').first()
  const thomas = grid.getByRole('button', { name: /^Thomas classique/ })
  await thomas.click()
  const dialog = page.getByRole('dialog'), pile = dialog.locator('.collection-stack-content')
  await expect(pile).toBeVisible()
  await dialog.evaluate(el => { el.scrollTop = 650 })
  await expect.poll(() => dialog.evaluate(el => el.scrollTop)).toBeGreaterThan(600)
  const card = pile.locator('.card:visible').filter({ has: page.locator('img') })
  // Pick a card actually inside the scrolled dialog viewport.
  const index = await card.evaluateAll(elements => elements.findIndex(el => { const r = el.getBoundingClientRect(), d = el.closest('dialog')!.getBoundingClientRect(); return r.top > d.top && r.bottom < d.bottom }))
  const selected = (await card.nth(index).elementHandle())!
  await selected.evaluate(el => { (el.querySelector('img') as HTMLElement).dataset.retained = 'yes' })
  await selected.evaluate(el => el.addEventListener('pointerdown', () => { (el as HTMLElement).dataset.clickScroll = String(el.closest('dialog')!.scrollTop) }, {once:true}))
  await selected.click()
  const scroll = Number(await selected.getAttribute('data-click-scroll'))
  await expect(pile).toBeHidden()
  await expect(pile.locator('img[data-retained="yes"]')).toHaveCount(1)
  await expect(dialog.locator('.detail-card .card')).toBeVisible()
  await dialog.getByRole('button', { name: 'Retour à la pile', exact: true }).click()
  await expect(pile.locator('img[data-retained="yes"]')).toBeVisible()
  await expect.poll(() => dialog.evaluate(el => el.scrollTop)).toBeCloseTo(scroll, 0)
  await selected.click()
  await dialog.getByRole('button', { name: 'Fermer', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.stack-grid')).toHaveCount(0)
  // A different pile starts with fresh state after closing the detail directly.
  await grid.getByRole('button', { name: /^Matthieu classique/ }).click()
  await expect(dialog).toContainText('Matthieu classique')
  await expect(dialog.locator('.stack-grid .collection-item')).toHaveCount(2)
  await expect.poll(() => dialog.evaluate(el => el.scrollTop)).toBe(0)
  await dialog.locator('.stack-grid .card').first().click()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.stack-grid')).toHaveCount(0)
  await thomas.click()
  await dialog.locator('.stack-grid .card').first().click()
  await page.mouse.click(0, 0)
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.stack-grid')).toHaveCount(0)
  await thomas.click()
  await dialog.locator('.stack-grid .card').first().click()
  await dialog.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect(page).toHaveURL(/\/envoyer\//)
  await expect(page.locator('.stack-grid')).toHaveCount(0)
})
