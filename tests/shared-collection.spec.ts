async function prepare(page: Page) {
  await page.goto('/echanges')
  await expect(page.getByRole('heading', { name: 'Amis', exact: true })).toBeVisible()
  return page.evaluate(async () => {
    const databasePath = '/src/storage/database.ts', cryptoPath = '/src/exchanges/crypto.ts', servicesPath = '/src/exchanges/services.ts', collectionPath = '/src/collection/collectionCrypto.ts'
    const { db } = await import(databasePath), { generateIdentity, createContactCode } = await import(cryptoPath), { addContact } = await import(servicesPath), { signCollection } = await import(collectionPath)
    const identity = await generateIdentity()
    await addContact(createContactCode(identity), 'Nana')
    const variants = [
      { cardId: 't-classique', finish: 'normal', artVariant: 'standard', quantity: 3, favorite: true },
      { cardId: 't-classique', finish: 'glossy', artVariant: 'fullArt', quantity: 2, favorite: false },
      { cardId: 'nana-diff', finish: 'alternative', artVariant: 'fullArt', quantity: 1, favorite: true },
    ]
    await db.drops.add({ dropId: crypto.randomUUID(), cardId: 't-classique', finish: 'normal', artVariant: 'standard', status: 'owned', acquiredAt: 1, updatedAt: 1 })
    const now = Math.floor(Date.now() / 1000)
    return { code: await signCollection(identity, variants, now), older: await signCollection(identity, variants, now - 10), future: await signCollection(identity, variants, now + 48 * 3600), sameTime: await signCollection(identity, variants.map((entry, i) => i === 0 ? { ...entry, quantity: 4 } : entry), now), senderId: identity.playerUuid }
  })
}
async function openProfile(page: Page) {
  const profile = page.getByRole('dialog', { name: 'Fiche ami', exact: true })
  if (!await profile.isVisible()) await page.getByRole('button', { name: 'Voir la fiche de Nana', exact: true }).click()
  return profile
}
async function pasteCollection(page: Page, code: string) {
  await page.evaluate(value => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { readText: async () => value, writeText: async () => {} } }), code)
  await page.getByRole('button', { name: 'Coller le code', exact: true }).click()
}
async function receive(page: Page, code: string) {
  await openProfile(page)
  await page.getByRole('button', { name: /^(Recevoir sa collection|Mettre à jour sa collection)$/ }).click()
  const input = page.getByRole('dialog', { name: 'Recevoir la collection de Nana', exact: true })
  await pasteCollection(page, code)
  await input.getByRole('button', { name: 'Recevoir', exact: true }).click()
}
async function memoryKeys(page: Page) { return page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('bizave.collectionMemory.v1.'))) }
async function gameState(page: Page) {
  return page.evaluate(async () => {
    const path = '/src/storage/database.ts', { db } = await import(path)
    return JSON.stringify(await Promise.all(['drops', 'discoveries', 'favorites', 'outbox', 'usedTransfers', 'player'].map(name => db.table(name).toArray())))
  })
}
async function enableMemory(page: Page) {
  await page.goto('/parametres'); await expandSettings(page, 'collection')
  await page.getByRole('switch', { name: 'Collection en mémoire', exact: true }).click()
  await page.goto('/echanges')
}

